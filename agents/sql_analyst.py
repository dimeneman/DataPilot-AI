_SCHEMA_CACHE: Optional[str] = None

def get_connection_details() -> dict:
    """Reads PostgreSQL connection details from environment variables."""
    return {
        "host": os.getenv("DB_HOST", "localhost"),
        "port": int(os.getenv("DB_PORT", 5432)),
        "user": os.getenv("DB_USER"),
        "password": os.getenv("DB_PASSWORD"),
        "dbname": os.getenv("DB_NAME"),
    }

def get_db_schema() -> str:
    """Fetches and caches the database schema."""
    global _SCHEMA_CACHE
    if not _SCHEMA_CACHE:
        logger.info("Fetching and caching database schema...")
        db = DatabaseUtil(get_connection_details())
        _SCHEMA_CACHE = db.schema_details("public")
    return _SCHEMA_CACHE

# =============================================================================
# Gemini Helpers
# =============================================================================

def extract_text(response) -> str:
    """
    Extract plain text safely from Gemini response.
    Handles both string and list content structures.
    """
    content = response.content

    if isinstance(content, str):
        return content.strip()

    if isinstance(content, list):
        texts = []
        for item in content:
            if isinstance(item, str):
                texts.append(item)
            elif isinstance(item, dict) and "text" in item:
                texts.append(item["text"])
        return "\n".join(texts).strip()

    return str(content).strip()

def clean_sql(sql: str) -> str:
    """
    Remove markdown formatting (```sql ... ```) generated by LLM.
    """
    sql = sql.strip()
    
    # Safely extract content inside markdown blocks if they exist
    match = re.search(r"```(?:sql)?(.*?)```", sql, flags=re.IGNORECASE | re.DOTALL)
    if match:
        return match.group(1).strip()
        
    return re.sub(r"^```(?:sql)?\s*|\s*```$", "", sql, flags=re.IGNORECASE).strip()

def only_select_query(sql: str) -> bool:
    """
    Allow only SELECT/WITH queries and prevent stacked queries.
    """
    sql = sql.strip().lower()
    
    if ";" in sql and not sql.endswith(";"):
        return False
        
    return sql.startswith("select") or sql.startswith("with")

# =============================================================================
# Node 1 : Curate Question
# =============================================================================

def curate_ques(state: AgentSchema) -> AgentSchema:
    """Improve the user's question without changing its original meaning."""
    try:
        logger.info("Curating user question...")
        llm = pick_llm("low")

        prompt = f"""You are an expert data analyst.
Rewrite the user's question ONLY if it improves clarity for SQL generation.
RULES:
1. Preserve original intent.
2. Do not answer or explain.
3. Return ONLY the rewritten question.

USER QUESTION: {state.user_question}"""

        response = llm.invoke(prompt)
        curated_question = extract_text(response)
        
        logger.info("Curated Question: %s", curated_question)
        
        state.curated_ques = curated_question
        
        # Ensure clean state message initialization
        if not hasattr(state, "messages") or state.messages is None:
            state.messages = []
            
        # Avoid duplication of the initial user message on retries
        if not state.messages or not isinstance(state.messages[0], HumanMessage):
            state.messages.append(HumanMessage(content=state.user_question))
            
        state.messages.append(AIMessage(content=f"Curated: {curated_question}"))
        
    except Exception as e:
        logger.exception("Error in curate_ques: %s", e)
        state.final_answer = f"Error processing question: {str(e)}"
        
    return state

# =============================================================================
# Node 2 : Build SQL Prompt
# =============================================================================

def prompt_query_context(state: AgentSchema) -> AgentSchema:
    """Builds the prompt that will be given to the SQL generation model."""
    try:
        schema_info = get_db_schema()

        prompt = f"""You are an expert PostgreSQL SQL Generator.
Convert the user's question into a PostgreSQL query.

RULES:
1. Return ONLY executable SQL. No explanations, no markdown styling.
2. Unless explicitly asked, LIMIT the result to 10 rows.
3. Use ONLY tables and columns explicitly present in the schema.
4. Never hallucinate table names.
5. Generate PostgreSQL compatible SQL only.

USER QUESTION:
{state.curated_ques}

DATABASE SCHEMA:
{schema_info}
"""
        state.prompt_query_context = prompt
        logger.info("SQL generation prompt created successfully.")
    except Exception as e:
        logger.exception("Error in prompt_query_context: %s", e)
        state.final_answer = f"Error building context: {str(e)}"

    return state

# =============================================================================
# Node 3 : Generate SQL
# =============================================================================

def generate_sql(state: AgentSchema) -> AgentSchema:
    """Generates SQL from the prompt."""
    try:
        logger.info("Generating SQL...")
        llm = pick_llm("medium")
        
        response = llm.invoke(state.prompt_query_context)
        generated_sql = clean_sql(extract_text(response))
        
        state.generated_sql_query = generated_sql
        logger.info("Generated SQL:\n%s", generated_sql)
        
        state.messages.append(AIMessage(content=f"SQL: {generated_sql}"))
    except Exception as e:
        logger.exception("Error in generate_sql: %s", e)
        state.final_answer = f"Error generating SQL: {str(e)}"
        
    return state

# =============================================================================
# Node 4 : SQL Safety Judge
# =============================================================================

def is_safe_sql(state: AgentSchema) -> AgentSchema:
    """Determines whether the generated SQL is safe to execute."""
    try:
        sql_query = state.generated_sql_query

        if not only_select_query(sql_query):
            state.is_safe = "No"
            state.comments = "Rejected by deterministic validator: Only singular SELECT/WITH queries are allowed."
            logger.warning(state.comments)
            return state

        llm = pick_llm("medium")
        llm_judge = llm.with_structured_output(JudgeSchema)

        prompt = f"""You are an SQL Security Judge.
Determine if the SQL is safe (read-only). Reject ANY command that modifies data or schema.
UNSAFE: INSERT, UPDATE, DELETE, DROP, ALTER, CREATE, TRUNCATE, MERGE, GRANT, REVOKE, COPY, VACUUM, CALL, DO.
If it strictly reads data without mutation, answer Yes.

SQL TO EVALUATE:
{sql_query}
"""
        result = llm_judge.invoke(prompt).model_dump()
        state.is_safe = result.get("answer", "No")
        state.comments = result.get("comments", "No comments provided.")

        logger.info("Judge Decision: %s | Comments: %s", state.is_safe, state.comments)
        state.messages.append(
            AIMessage(content=f"Judge: {state.is_safe} - {state.comments}")
        )
    except Exception as e:
        logger.exception("Error in is_safe_sql: %s", e)
        state.is_safe = "No"
        state.comments = str(e)
        state.final_answer = f"Validation error: {str(e)}"
        
    return state

# =============================================================================
# Node 5 : Cancel SQL Execution
# =============================================================================

def canceled_sql(state: AgentSchema) -> AgentSchema:
    """Called when the generated SQL is unsafe."""
    logger.warning("Unsafe SQL detected. Execution cancelled.")
    state.final_answer = f"The generated SQL query was **not executed** because it was considered unsafe.\n\nReason: {state.comments}"
    state.messages.append(AIMessage(content="Execution Canceled."))
    return state

# =============================================================================
# Node 6 : Execute SQL
# =============================================================================

def execute_sql(state: AgentSchema) -> AgentSchema:
    """Execute the generated SQL query."""
    try:
        logger.info("Executing SQL query...")
        db = DatabaseUtil(get_connection_details())
        execution_result = db.execute_sql(state.generated_sql_query)
        
        state.sql_query_execution_result = execution_result
        logger.info("SQL executed successfully.")
        
        # Keep history clean; don't dump massive execution results if not needed
        state.messages.append(AIMessage(content="SQL Executed Successfully."))
    except Exception as e:
        logger.exception("Error in execute_sql: %s", e)
        state.sql_query_execution_result = None
        state.final_answer = f"Database execution failed.\n\n{str(e)}"
        
    return state

# =============================================================================
# Node 7 : Represent Final Answer
# =============================================================================

def represent_final_answer(state: AgentSchema) -> AgentSchema:
    """Convert SQL output into a user-friendly answer."""
    if state.final_answer and ("failed" in state.final_answer.lower() or "not executed" in state.final_answer.lower()):
        return state

    try:
        logger.info("Generating final natural language answer...")
        llm = pick_llm("low")

        prompt = f"""You are a professional Data Analyst.
Answer the user's question naturally using the provided execution result.

RULES:
- Do NOT mention SQL, databases, or tables.
- Do NOT explain how the answer was obtained.
- Summarize multiple rows using bullet points.
- If the result is empty, politely state no matching data exists.

USER QUESTION: {state.curated_ques}
EXECUTION RESULT: {state.sql_query_execution_result}"""

        response = llm.invoke(prompt)
        final_answer = extract_text(response)
        
        state.final_answer = final_answer
        state.messages.append(AIMessage(content=f"Final Answer: {final_answer}"))
        logger.info("Final answer generated successfully.")
    except Exception as e:
        logger.exception("Error in represent_final_answer: %s", e)
        state.final_answer = f"Error formatting final answer: {str(e)}"
        
    return state


# =============================================================================
# GRAPH ROUTING & COMPILATION
# =============================================================================

def route_safety(state: AgentSchema) -> str:
    """Routes execution based on the safety judge's decision."""
    return "execute_sql" if state.is_safe.lower() == "yes" else "canceled_sql"

workflow = StateGraph(AgentSchema)

# Add Nodes explicitly via string names
workflow.add_node("curate_ques", curate_ques)
workflow.add_node("prompt_query_context", prompt_query_context)
workflow.add_node("generate_sql", generate_sql)
workflow.add_node("is_safe_sql", is_safe_sql)
workflow.add_node("canceled_sql", canceled_sql)
workflow.add_node("execute_sql", execute_sql)
workflow.add_node("represent_final_answer", represent_final_answer)

# Add Edges ensuring complete visualization flow
workflow.add_edge(START, "curate_ques")
workflow.add_edge("curate_ques", "prompt_query_context")
workflow.add_edge("prompt_query_context", "generate_sql")
workflow.add_edge("generate_sql", "is_safe_sql")

# Dictionary mapping specifies node targets for graph visualization
workflow.add_conditional_edges(
    "is_safe_sql", 
    route_safety,
    {
        "execute_sql": "execute_sql",
        "canceled_sql": "canceled_sql"
    }
)

workflow.add_edge("execute_sql", "represent_final_answer")
workflow.add_edge("represent_final_answer", END)
workflow.add_edge("canceled_sql", END)

# Compile Graph
sql_analyst = workflow.compile()


